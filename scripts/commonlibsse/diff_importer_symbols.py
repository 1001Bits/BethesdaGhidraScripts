#!/usr/bin/env python3
"""Diff the per-runtime symbol offsets of two generated CommonLibSSE importers.

Written for the 2026-09-21 Skyrim 1.7.104 incident: the generator resolved
SE-only symbols through the AE-namespace 1.7.104 database, so every such symbol
carried an unrelated RVA.  Comparing the old importer with one regenerated by
the fixed generator yields the exact ``(name, wrong RVA, correct RVA or none)``
list that a program which imported the old script has to be cleaned of.

Pure Python; reads the two scripts as text and never executes them.

Usage:
  python diff_importer_symbols.py OLD.py NEW.py --runtime 17104 --out wrong.csv
"""
from __future__ import annotations

import argparse
import ast
import csv
import json
import re
import sys

_TABLE = re.compile(
    r"^(SYMBOLS|FALLBACK_SYMBOLS) = _json\w*\.loads\((?P<literal>.*)\)\s*$")


def load_symbols(path):
    """{table: [symbol dict, ...]} from a generated importer."""
    tables = {}
    with open(path, encoding="utf-8") as handle:
        for line in handle:
            match = _TABLE.match(line)
            if match:
                tables[match.group(1)] = json.loads(
                    ast.literal_eval(match.group("literal")))
    missing = {"SYMBOLS", "FALLBACK_SYMBOLS"} - set(tables)
    if missing:
        raise SystemExit("{}: no {} table".format(path, sorted(missing)))
    return tables


def _key(symbol, rva):
    # What an importer leaves in the program is a NAME at an ADDRESS.  Which
    # table (SYMBOLS / FALLBACK_SYMBOLS) or which ID produced it does not
    # change that label, so a symbol that merely moved between tables at the
    # same RVA is not wrong and must never be offered to the remover.
    return (symbol["n"], int(rva))


def placements(tables, runtime):
    """{(name, rva): (table, symbol)} for every symbol carrying a ``runtime``
    offset; the first symbol seen describes a placement made twice."""
    out = {}
    for table, symbols in tables.items():
        for symbol in symbols:
            rva = symbol.get(runtime)
            if rva is None:
                continue
            out.setdefault(_key(symbol, rva), (table, symbol))
    return out


def wrong_rows(old_tables, new_tables, runtime):
    """Rows for every (name, rva) the old importer placed and the new one does
    not.  ``correct_rva`` lists where the new importer puts that name."""
    old = placements(old_tables, runtime)
    new = placements(new_tables, runtime)
    new_rvas = {}
    for name, rva in new:
        new_rvas.setdefault(name, set()).add(rva)
    rows = []
    for key in sorted(old):
        if key in new:
            continue
        name, rva = key
        table, symbol = old[key]
        rows.append({
            "name": name, "kind": symbol.get("t", ""), "table": table,
            "wrong_rva": "0x%X" % rva,
            "correct_rva": "|".join(
                "0x%X" % value for value in sorted(new_rvas.get(name, ()))),
            "se_id": symbol.get("si") if symbol.get("si") is not None else "",
            "ae_id": symbol.get("ai") if symbol.get("ai") is not None else "",
            "source": symbol.get("src", ""),
        })
    return rows, old, new


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("old")
    ap.add_argument("new")
    ap.add_argument("--runtime", required=True,
                    help="offset key inside the symbol dicts, e.g. 17104")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    rows, old, new = wrong_rows(load_symbols(args.old), load_symbols(args.new),
                                args.runtime)
    with open(args.out, "w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=[
            "name", "kind", "table", "wrong_rva", "correct_rva", "se_id",
            "ae_id", "source"])
        writer.writeheader()
        writer.writerows(rows)

    removed = sum(1 for row in rows if not row["correct_rva"])
    print("{} (name, rva) placements for {} in the old importer, {} in the new".format(
        len(old), args.runtime, len(new)))
    print("{} differ: {} have no {} address at all, {} moved".format(
        len(rows), removed, args.runtime, len(rows) - removed))
    print("only in new: {}".format(len(set(new) - set(old))))
    print("-> " + args.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
